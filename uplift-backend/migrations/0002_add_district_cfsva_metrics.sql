-- District food security, dietary diversity, malnutrition and
-- agricultural-vulnerability layer (WFP/NISR CFSVA 2024).
--
-- SAFETY: no existing table or column is altered, renamed or dropped.
-- The new table links to the canonical district keys via a foreign key on
-- regions.id. (Exact string matching on district names was NOT used as the
-- join; regions.id is the authoritative district key already shared by
-- survey_metrics, and the seeder inserts exactly the 30 canonical names.)
-- History: temporarily named district_food_security during development;
-- renamed to district_cfsva_metrics before any production consumer existed.
-- Applied automatically by models.Base.metadata.create_all / seed_cfsva.py.
-- =====================================================================

CREATE TABLE IF NOT EXISTS district_cfsva_metrics (
    id                       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    region_id                BIGINT NOT NULL REFERENCES regions (id) ON DELETE CASCADE,
    survey_year              INTEGER NOT NULL,

    -- Food security & consumption (WFP/IPC scale)
    fies_moderate_severe_pct DOUBLE PRECISION NOT NULL,   -- moderate + severe food insecurity, %
    fies_severe_pct          DOUBLE PRECISION NOT NULL,   -- severely food insecure, %
    food_consumption_score   DOUBLE PRECISION NOT NULL,   -- mean Food Consumption Score (0-112 pts)
    fcs_poor_pct             DOUBLE PRECISION NOT NULL,   -- share with poor FCS, %

    -- Dietary diversity
    hdds                     DOUBLE PRECISION NOT NULL,   -- mean Household Dietary Diversity Score (0-12)

    -- Malnutrition (children under five)
    stunting_pct             DOUBLE PRECISION NOT NULL,
    wasting_pct              DOUBLE PRECISION NOT NULL,

    -- Agricultural vulnerability / stress
    rcsi                     DOUBLE PRECISION NOT NULL,   -- Reduced Coping Strategies Index (lower is better)
    harvest_loss_pct         DOUBLE PRECISION NOT NULL,   -- households with >= 1 harvest loss, %
    CONSTRAINT uq_cfsva_region_year UNIQUE (region_id, survey_year)
);

CREATE INDEX IF NOT EXISTS ix_cfsva_region_id ON district_cfsva_metrics (region_id);

COMMENT ON TABLE district_cfsva_metrics IS
    'CFSVA 2024 layer (WFP/NISR). Keyed to regions.id; FinScope/EICV7 tables untouched.';
